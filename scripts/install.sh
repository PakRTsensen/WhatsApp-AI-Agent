#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

log() { printf '\n==> %s\n' "$*"; }
die() { printf '\nERROR: %s\n' "$*" >&2; exit 1; }

command -v node >/dev/null 2>&1 || die "Node.js is required (>= 20)."
command -v npm >/dev/null 2>&1 || die "npm is required."
command -v python3 >/dev/null 2>&1 || die "python3 is required."

NODE_MAJOR="$(node -p "Number(process.versions.node.split('.')[0])")"
[ "$NODE_MAJOR" -ge 20 ] || die "Node.js >= 20 is required (found $(node -v))."

OPENCODE_BIN="${NOPPO_OPENCODE_BINARY:-$(command -v opencode || true)}"
[ -n "$OPENCODE_BIN" ] || die "OpenCode CLI not found. Install it first or set NOPPO_OPENCODE_BINARY."
if [ "${OPENCODE_BIN#/}" = "$OPENCODE_BIN" ]; then
    OPENCODE_BIN="$(command -v "$OPENCODE_BIN" || true)"
fi
[ -n "$OPENCODE_BIN" ] || die "OpenCode CLI not found on PATH."
"$OPENCODE_BIN" --version >/dev/null 2>&1 || die "OpenCode at $OPENCODE_BIN is not runnable."

mkdir -p "$ROOT/logs"

log "Installing Node dependencies"
npm install --no-audit --no-fund

log "Preparing Python MCP environment"
if [ ! -x "$ROOT/mcp/.venv/bin/python" ]; then
    python3 -m venv "$ROOT/mcp/.venv"
fi
"$ROOT/mcp/.venv/bin/python" -m pip install --quiet --upgrade pip
"$ROOT/mcp/.venv/bin/pip" install --quiet -r "$ROOT/mcp/requirements.txt"

ENV_FILE="$ROOT/control/noppo.env"
if [ -f "$ENV_FILE" ] && [ "${NOPPO_FORCE_ENV:-0}" != "1" ]; then
    log "Keeping existing $ENV_FILE (set NOPPO_FORCE_ENV=1 to rewrite)"
else
    DETECTED_URL=""
    DETECTED_KEY=""
    GLOBAL_CFG="${OPENCODE_CONFIG:-$HOME/.config/opencode/opencode.json}"
    if [ -f "$GLOBAL_CFG" ]; then
        eval "$(python3 - "$GLOBAL_CFG" <<'PY'
import json, shlex, sys
try:
    data = json.load(open(sys.argv[1]))
except Exception:
    data = {}
options = (data.get('provider', {}).get('9router', {}) or {}).get('options', {}) or {}
url = options.get('baseURL') or options.get('baseUrl') or ''
key = options.get('apiKey') or ''
print('DETECTED_URL=' + shlex.quote(str(url)))
print('DETECTED_KEY=' + shlex.quote(str(key)))
PY
)"
    fi

    OWNER="${BOT_OWNER_NUMBERS:-}"
    if [ -z "$OWNER" ]; then
        [ -t 0 ] || die "Set BOT_OWNER_NUMBERS (comma separated) or run interactively."
        read -r -p "Owner WhatsApp number(s), comma separated: " OWNER
    fi
    [ -n "$OWNER" ] || die "At least one owner number is required."

    BOT_NUMBER="${BOT_NUMBER:-$(printf '%s' "$OWNER" | cut -d, -f1 | tr -cd '0-9')}"
    if [ -t 0 ]; then
        read -r -p "Bot WhatsApp number [$BOT_NUMBER]: " INPUT_BOT
        BOT_NUMBER="${INPUT_BOT:-$BOT_NUMBER}"
    fi

    PAIRING_NUMBER="${PAIRING_NUMBER:-}"
    if [ -t 0 ]; then
        read -r -p "Pairing number (blank = QR code) [$PAIRING_NUMBER]: " INPUT_PAIRING
        PAIRING_NUMBER="${INPUT_PAIRING:-$PAIRING_NUMBER}"
    fi

    ROUTER_URL="${NOPPO_ROUTER_URL:-$DETECTED_URL}"
    if [ -z "$ROUTER_URL" ]; then
        ROUTER_URL="http://127.0.0.1:20128/v1"
    fi
    if [ -t 0 ]; then
        read -r -p "Router base URL [$ROUTER_URL]: " INPUT_URL
        ROUTER_URL="${INPUT_URL:-$ROUTER_URL}"
    fi

    ROUTER_KEY="${NOPPO_ROUTER_API_KEY:-$DETECTED_KEY}"
    if [ -z "$ROUTER_KEY" ] && [ -t 0 ]; then
        read -r -s -p "Router API key (Enter to skip): " ROUTER_KEY
        printf '\n'
    fi
    if [ -z "$ROUTER_KEY" ]; then
        printf 'WARNING: no router API key. OpenCode still works, but image analysis will fail.\n' >&2
    fi

    ENGINE_PROVIDER="${NOPPO_ENGINE_PROVIDER:-9router}"

    umask 077
    {
        printf '# Generated by scripts/install.sh on %s\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
        printf "BOT_OWNER_NUMBERS='%s'\n" "$OWNER"
        printf "BOT_NUMBER='%s'\n" "$BOT_NUMBER"
        printf "PAIRING_NUMBER='%s'\n" "$PAIRING_NUMBER"
        printf "NOPPO_OPENCODE_BINARY='%s'\n" "$OPENCODE_BIN"
        printf "NOPPO_ENGINE_PROVIDER='%s'\n" "$ENGINE_PROVIDER"
        printf "NOPPO_AGENT='%s'\n" "${NOPPO_AGENT:-noppo}"
        printf "NOPPO_WORKDIR='%s'\n" "$ROOT"
        printf "NOPPO_ROUTER_URL='%s'\n" "$ROUTER_URL"
        printf "NOPPO_ROUTER_API_KEY='%s'\n" "$ROUTER_KEY"
    } > "$ENV_FILE"
    chmod 600 "$ENV_FILE"
    log "Wrote $ENV_FILE"
fi

log "Running the test suite"
npm test

if command -v pm2 >/dev/null 2>&1; then
    log "PM2 detected. Start with: pm2 start ecosystem.config.js && pm2 save"
else
    log "PM2 not detected. Install it with: npm install -g pm2"
fi

log "Done. Next steps"
cat <<EOF
  1. Pair WhatsApp (first run): pm2 start ecosystem.config.js && pm2 logs noppo-agent --nostream
  2. Enter the pairing code in WhatsApp > Linked devices.
  3. Verify MCP: $OPENCODE_BIN mcp list
EOF
